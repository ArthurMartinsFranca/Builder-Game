export function desenharMapa(ctx) {
    for (let i = 0; i < MAPA.length; i++) {
        for (let j = 0; j < MAPA[i].length; j++) {
            const blocoX = j * TAMANHObLOCO;
            const blocoY = i * TAMANHObLOCO;

            ctx.fillStyle = MAPA[i][j] === 1
                ? "#228B22"
                : "#555";

            ctx.fillRect(
                blocoX,
                blocoY,
                TAMANHObLOCO,
                TAMANHObLOCO
            );
        }
    }
}

