export function desenharMapa(ctx) {
    for (let i = 0; i < MAPA.length; i++) {
        for (let j = 0; j < MAPA[i].length; j++) {
            const blocoX = j * TAMANHObLOCO;
            const blocoY = i * TAMANHObLOCO;

            let sprite;

            if (MAPA[i][j] === 0) {
                sprite = spritePedra;
            } else if (MAPA[i][j] === 1) {
                sprite = spriteGrama;
            } else if (MAPA[i][j] === 2) {
                sprite = spriteArvore;
            }

            if (sprite && sprite.complete && sprite.naturalWidth > 0) {
                ctx.drawImage(
                    sprite,
                    blocoX,
                    blocoY,
                    TAMANHObLOCO,
                    TAMANHObLOCO
                );
            }
        }
    }
}


